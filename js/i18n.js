export class I18nManager {
  constructor() {
    this.currentLang = 'vi';
    this.listeners = [];
    this.beforeListeners = [];
  }

  init() {
    const saved = localStorage.getItem('ethere_lang');
    if (saved && TRANSLATIONS[saved]) {
      this.currentLang = saved;
    } else {
      this.currentLang = 'vi';
    }

    this.bindLanguageSwitcher();
    this.applyLanguage(this.currentLang, false);
  }

  bindLanguageSwitcher() {
    const buttons = document.querySelectorAll('.utility-lang .lang-item');
    buttons.forEach((btn) => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const lang = btn.getAttribute('data-lang')?.toLowerCase();
        if (lang && TRANSLATIONS[lang] && lang !== this.currentLang) {
          this.setLanguage(lang);
        }
      });
    });
  }

  setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('ethere_lang', lang);
    this.applyLanguage(lang, true);
  }

  applyLanguage(lang, animate = true) {
    // Notify before-listeners (e.g. cleanly revert SplitText before DOM text is rewritten)
    this.beforeListeners.forEach((fn) => fn(lang));

    document.documentElement.lang = lang;

    // Update active button state
    document.querySelectorAll('.utility-lang .lang-item').forEach((btn) => {
      const isCurrent = btn.getAttribute('data-lang')?.toLowerCase() === lang;
      if (isCurrent) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    const dict = TRANSLATIONS[lang];
    if (!dict) return;

    // Update elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = dict[key];
        } else if (dict[key].includes('<')) {
          el.innerHTML = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // Notify listeners
    this.listeners.forEach((fn) => fn(lang));
  }

  onBeforeLanguageChange(fn) {
    this.beforeListeners.push(fn);
  }

  onLanguageChange(fn) {
    this.listeners.push(fn);
  }

  t(key, fallback = null) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.vi;
    if (dict && key in dict) return dict[key];
    const viDict = TRANSLATIONS.vi;
    if (viDict && key in viDict) return viDict[key];
    return fallback !== null ? fallback : key;
  }

  tRoute(routeName) {
    const titles = ROUTE_TITLES[this.currentLang] || ROUTE_TITLES.vi;
    return titles[routeName] || titles.home;
  }

  getRoomLocalization(roomId) {
    if (!roomId) return null;
    const num = String(roomId).trim().toUpperCase();
    const map = { '1': 'I', '2': 'II', '3': 'III', '4': 'IV' };
    const key = map[num] || num;
    const langDict = ROOM_LOCALIZATIONS[this.currentLang] || ROOM_LOCALIZATIONS.vi;
    return langDict[key] || ROOM_LOCALIZATIONS.vi[key] || null;
  }

  getStoryLocalization(storyId) {
    if (!storyId) return null;
    const id = String(storyId).trim().toLowerCase().replace(/^story\//, '');
    const langDict = STORY_LOCALIZATIONS[this.currentLang] || STORY_LOCALIZATIONS.vi;
    return langDict[id] || STORY_LOCALIZATIONS.vi[id] || null;
  }

  getCuratorialParagraphs() {
    return CURATORIAL_STATEMENT_PARAGRAPHS[this.currentLang] || CURATORIAL_STATEMENT_PARAGRAPHS.vi;
  }
}

export const i18n = new I18nManager();
